// The flat reservation on OP Sepolia against the deployed contracts, with the real cost of every
// transaction (L2 execution gas and fee, L1 data fee). Writes design/OP-SEPOLIA-RUN.md.
//
// Usage: PRIVATE_KEY in ../.env (a funded OP Sepolia account), then   node eval/op-sepolia.ts
import { writeFileSync } from 'node:fs';
import { ethers } from 'ethers';
import type { ContractName } from '../src/chain/client.ts';
import { connectLive, txCost, type TxCost } from '../src/chain/live.ts';
import { runFlatReservation } from './flat-reservation.ts';

const ROOT = new URL('../../', import.meta.url);
const OUT = new URL('design/OP-SEPOLIA-RUN.md', ROOT);

const median = (xs: bigint[]): bigint => [...xs].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0))[Math.floor(xs.length / 2)]!;
const eth = (wei: bigint): string => ethers.formatEther(wei);

async function main(): Promise<void> {
  const { dep, provider, wallet, d } = await connectLive();
  const before = await provider.getBalance(wallet.address);
  const tag = `-${Date.now().toString(36)}`;
  const started = new Date();

  const result = await runFlatReservation(dep.rpc, { signer: wallet, deployment: d, tag });
  const after = await provider.getBalance(wallet.address);

  // name every transaction by contract and function
  const byAddress = new Map<string, [string, ethers.Interface]>();
  for (const k of Object.keys(dep.contracts) as ContractName[]) byAddress.set(dep.contracts[k].toLowerCase(), [k, d[k].interface]);
  const rows: (TxCost & { fn: string })[] = [];
  for (const s of wallet.sent) {
    const [name, iface] = byAddress.get((s.to ?? '').toLowerCase()) ?? ['?', undefined];
    const fn = iface?.parseTransaction({ data: s.data })?.name ?? s.data.slice(0, 10);
    rows.push({ ...(await txCost(provider, s.hash)), fn: `${name}.${fn}` });
  }

  const groups = new Map<string, typeof rows>();
  for (const r of rows) groups.set(r.fn, [...(groups.get(r.fn) ?? []), r]);
  const sum = (xs: bigint[]) => xs.reduce((a, b) => a + b, 0n);
  const totalL2 = sum(rows.map((r) => r.l2Fee)), totalL1 = sum(rows.map((r) => r.l1Fee));

  const md: string[] = [
    '# Flat reservation on OP Sepolia',
    '',
    `Run \`${tag.slice(1)}\`, ${started.toISOString()}, against the contracts in [\`DEPLOYMENTS.md\`](DEPLOYMENTS.md)`,
    `(generated by \`offchain/eval/op-sepolia.ts\`). Sender \`${wallet.address}\`, ${rows.length} transactions,`,
    `blocks ${Math.min(...rows.map((r) => r.block))}–${Math.max(...rows.map((r) => r.block))}.`,
    '',
    '## Outcome',
    '',
    '| Check | Result |',
    '|---|---|',
    `| naive profile books the flat twice | ${result.naiveDoubleBooking} |`,
    `| CAS profile rejects the second guarded revocation | ${result.casRejected ?? 'not rejected'} |`,
    `| loser's proof ∃x∈S. Revoked(x) valid | ${result.loserProofValid} |`,
    `| loser's proof still valid after later updates | ${result.loserProofStillValidLater} |`,
    `| holder proves "one of S, revoked" without saying which | ${result.holderReservationProof} |`,
    '',
    '```',
    ...result.log,
    '```',
    '',
    '## Gas and fees per operation',
    '',
    'Gas is L2 execution gas (the same as on anvil for the same call); the fee is L2 execution plus the L1 data fee.',
    '',
    '| Operation | Txs | Gas (median) | Gas (min–max) | L2 fee (ETH, total) | L1 data fee (ETH, total) |',
    '|---|---:|---:|---:|---:|---:|',
  ];
  for (const [fn, rs] of groups) {
    const g = rs.map((r) => r.gasUsed);
    const lo = g.reduce((a, b) => (b < a ? b : a)), hi = g.reduce((a, b) => (b > a ? b : a));
    md.push(`| ${fn} | ${rs.length} | ${median(g).toLocaleString('en')} | ${lo === hi ? '–' : `${lo.toLocaleString('en')}–${hi.toLocaleString('en')}`} | ${eth(sum(rs.map((r) => r.l2Fee)))} | ${eth(sum(rs.map((r) => r.l1Fee)))} |`);
  }
  md.push(
    '',
    `Total: ${sum(rows.map((r) => r.gasUsed)).toLocaleString('en')} gas, L2 fee ${eth(totalL2)} ETH, L1 data fee ${eth(totalL1)} ETH,`,
    `balance change ${eth(before - after)} ETH. Rejected calls (the stale guarded revocation, the unguarded revocation`,
    'under a bound policy) fail at gas estimation and are never sent, so they cost nothing.',
    '',
    '## Transactions',
    '',
    '| # | Operation | Block | Gas | Hash |',
    '|---:|---|---:|---:|---|',
    ...rows.map((r, i) => `| ${i + 1} | ${r.fn} | ${r.block} | ${r.gasUsed.toLocaleString('en')} | [\`${r.hash.slice(0, 10)}…\`](${dep.explorer}/tx/${r.hash}) |`),
    '',
  );
  writeFileSync(OUT, md.join('\n'));
  console.log(`\n${rows.length} transactions, ${eth(before - after)} ETH; written ${OUT.pathname}`);
  if (rows.some((r) => !r.status)) throw new Error('a sent transaction failed');
}

main().catch((e) => { console.error(e); process.exit(1); });
